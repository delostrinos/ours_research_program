# parameters
import numpy as np
a_min, a_max = 0, 2
t_min, t_max = 0, 0.5
num_of_a = 30
num_of_t = 50
M = 3
N = 3

# generating the values of a, and the values of t
a_values = np.linspace(a_min, a_max, num_of_a)
t_values = np.linspace(t_min, t_max, num_of_t)

A_grid, T_grid = np.meshgrid(a_values, t_values)
a_flat = A_grid.flatten()
t_flat = T_grid.flatten()

b = np.exp(a_flat * t_flat)

columns = []
for m in range(M + 1):
    for n in range(N + 1):
        column = (a_flat ** m) * (t_flat ** n)
        columns.append(column)
D = np.column_stack(columns)

c = np.linalg.lstsq(D, b)

c

epsilon = 0.38
coeffs = c[0]
survivors = [j for j in range(len(coeffs)) if abs(coeffs[j]) >= epsilon]
print(survivors)

D_clean = D[:, survivors]
c_refined = np.linalg.lstsq(D_clean, b, rcond=None)
print(c_refined[0])

